// Merges lib/l10n/parts/<part>_<locale>.arb into lib/l10n/app_<locale>.arb
// (the files `flutter gen-l10n` reads). Pure Dart: no package imports.
//
//   dart run tool/merge_arb.dart            write the merged files
//   dart run tool/merge_arb.dart --check    fail when a merged file is stale
//
// Each part owns a key prefix so lanes never edit the same file; the merge
// fails on a duplicate key, a key outside its part's prefix, a key present in
// one locale only, or a stale/unknown part file.
import 'dart:convert';
import 'dart:io';

/// Part name -> key prefix its keys must start with (null: none of the other
/// prefixes). Order is the order of keys in the merged file.
const Map<String, String?> arbParts = {
  'app': null,
  'scan': 'scan',
  'playback': 'playback',
  'library': 'library',
};

/// Locale whose key set every other locale must match.
const String templateLocale = 'en';

const String generatedMarker = '@@x-generated';
const String generatedNote =
    'Generated by tool/merge_arb.dart from lib/l10n/parts/. Do not edit.';

/// Problem found while merging.
class ArbMergeException implements Exception {
  ArbMergeException(this.message);
  final String message;
  @override
  String toString() => message;
}

/// The merged file contents per locale, from the parts in [l10nDir]/parts.
Map<String, String> mergeArbParts(Directory l10nDir) {
  final partsDir = Directory('${l10nDir.path}/parts');
  if (!partsDir.existsSync()) {
    throw ArbMergeException('missing folder ${partsDir.path}');
  }
  final pattern = RegExp(r'^([a-z]+)_([a-zA-Z]+(?:_[a-zA-Z]+)?)\.arb$');
  final files = <String, Map<String, File>>{}; // locale -> part -> file
  for (final entity in partsDir.listSync().whereType<File>()) {
    final name = entity.uri.pathSegments.last;
    final match = pattern.firstMatch(name);
    if (match == null || !arbParts.containsKey(match.group(1))) {
      throw ArbMergeException('unknown part file "$name" in ${partsDir.path}');
    }
    (files[match.group(2)!] ??= {})[match.group(1)!] = entity;
  }
  if (!files.containsKey(templateLocale)) {
    throw ArbMergeException('no "$templateLocale" parts in ${partsDir.path}');
  }

  final merged = <String, Map<String, Object?>>{};
  for (final locale in files.keys.toList()..sort()) {
    merged[locale] = _mergeLocale(locale, files[locale]!);
  }

  final template = _messageKeys(merged[templateLocale]!);
  for (final entry in merged.entries) {
    if (entry.key == templateLocale) continue;
    final keys = _messageKeys(entry.value);
    final missing = template.difference(keys);
    final extra = keys.difference(template);
    if (missing.isNotEmpty) {
      throw ArbMergeException(
        '${entry.key}: missing keys present in $templateLocale: ${(missing.toList()..sort()).join(', ')}',
      );
    }
    if (extra.isNotEmpty) {
      throw ArbMergeException(
        '${entry.key}: keys not in $templateLocale: ${(extra.toList()..sort()).join(', ')}',
      );
    }
  }

  const encoder = JsonEncoder.withIndent('  ');
  return {
    for (final e in merged.entries) e.key: '${encoder.convert(e.value)}\n',
  };
}

Set<String> _messageKeys(Map<String, Object?> arb) =>
    arb.keys.where((k) => !k.startsWith('@')).toSet();

Map<String, Object?> _mergeLocale(String locale, Map<String, File> parts) {
  final out = <String, Object?>{
    '@@locale': locale,
    generatedMarker: generatedNote,
  };
  final owner = <String, String>{}; // message key -> part
  final prefixes = [for (final p in arbParts.values) ?p];
  for (final part in arbParts.keys) {
    final file = parts[part];
    if (file == null) {
      // A missing part is fine for a locale only when the template has none.
      continue;
    }
    final Object? decoded;
    try {
      decoded = jsonDecode(file.readAsStringSync());
    } on FormatException catch (e) {
      throw ArbMergeException('${file.path}: invalid JSON (${e.message})');
    }
    if (decoded is! Map<String, dynamic>) {
      throw ArbMergeException('${file.path}: not a JSON object');
    }
    for (final entry in decoded.entries) {
      final key = entry.key;
      if (key == '@@locale') continue;
      if (key.startsWith('@@')) {
        throw ArbMergeException(
          '${file.path}: global key "$key" is not allowed in a part',
        );
      }
      final message = key.startsWith('@') ? key.substring(1) : key;
      final prefix = arbParts[part];
      final ok = prefix != null
          ? message.startsWith(prefix)
          : !prefixes.any(message.startsWith);
      if (!ok) {
        throw ArbMergeException(
          '${file.path}: key "$key" is outside the "$part" part '
          '(${prefix != null ? 'must start with "$prefix"' : 'must not start with ${prefixes.map((p) => '"$p"').join(', ')}'})',
        );
      }
      if (!key.startsWith('@')) {
        final previous = owner[message];
        if (previous != null) {
          throw ArbMergeException(
            'duplicate key "$message" in parts "$previous" and "$part" ($locale)',
          );
        }
        owner[message] = part;
      } else if (owner[message] != part) {
        throw ArbMergeException(
          '${file.path}: metadata "$key" has no message "$message" in this part',
        );
      }
      if (out.containsKey(key)) {
        throw ArbMergeException('duplicate key "$key" ($locale)');
      }
      out[key] = entry.value;
    }
  }
  return out;
}

/// Writes (or with [check] verifies) the merged files. Returns the process
/// exit code.
int runMergeArb(Directory l10nDir, {required bool check, StringSink? out}) {
  final sink = out ?? stdout;
  final Map<String, String> merged;
  try {
    merged = mergeArbParts(l10nDir);
  } on ArbMergeException catch (e) {
    sink.writeln('merge_arb: $e');
    return 1;
  }
  var stale = false;
  for (final entry in merged.entries) {
    final file = File('${l10nDir.path}/app_${entry.key}.arb');
    final current = file.existsSync() ? file.readAsStringSync() : null;
    if (current == entry.value) continue;
    if (check) {
      stale = true;
      sink.writeln('merge_arb: ${file.path} is stale');
    } else {
      file.writeAsStringSync(entry.value);
      sink.writeln('merge_arb: wrote ${file.path}');
    }
  }
  if (stale) {
    sink.writeln(
      'merge_arb: run `dart run tool/merge_arb.dart && flutter gen-l10n`',
    );
    return 1;
  }
  return 0;
}

void main(List<String> args) {
  final check = args.contains('--check');
  final unknown = args.where((a) => a != '--check');
  if (unknown.isNotEmpty) {
    stderr.writeln('usage: dart run tool/merge_arb.dart [--check]');
    exit(64);
  }
  // Resolve relative to this file so it works from any directory.
  final root = File.fromUri(Platform.script).parent.parent;
  exit(runMergeArb(Directory('${root.path}/lib/l10n'), check: check));
}
